"""Install and control a systemd service for the current user's configuration."""

import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

from .config import ConfigError, xdg
from .logging import get_cli_logger

HEADER = '# Generated by reicloud-sync; edit application settings through reicloud.\n'


def unit_name(paths):
    key = hashlib.sha256(str(paths.config.resolve()).encode()).hexdigest()[:12]
    return f'reicloud-sync-{key}.service'


def unit_path(paths):
    return xdg('XDG_CONFIG_HOME', '.config') / 'systemd' / 'user' / unit_name(paths)


def quote(value, *, command=False):
    value = str(value)
    if any(ord(character) < 32 or ord(character) == 127 for character in value):
        raise ConfigError('Service paths and environment values must not contain control characters.')
    value = value.replace('\\', '\\\\').replace('"', '\\"').replace('%', '%%')
    if command:
        value = value.replace('$', '$$')
    return '"' + value + '"'


def render_unit(paths, jobs=2):
    executable = Path(sys.executable).absolute()
    search = os.environ.get('PATH', os.defpath).split(os.pathsep)
    search += ['/usr/local/bin', '/usr/bin', '/bin']
    search = list(dict.fromkeys(value for value in search if Path(value).is_absolute()))
    environment = {'PATH': os.pathsep.join(search), 'PYTHONUNBUFFERED': '1',
                   'XDG_STATE_HOME': str(paths.state.parent),
                   'XDG_CACHE_HOME': str(paths.cache.parent)}
    command = [str(executable), '-m', 'reicloud_sync', '--config-dir', str(paths.config),
               'run', '--jobs', str(jobs)]
    lines = [HEADER, '[Unit]\n', 'Description=Reicloud personal cloud synchronization\n',
             '\n[Service]\n', 'Type=simple\n', 'UMask=0077\n']
    lines += [f'Environment={quote(key + "=" + value)}\n' for key, value in environment.items()]
    lines += ['ExecStart=' + ' '.join(quote(value, command=True) for value in command) + '\n',
              'Restart=on-failure\n', 'RestartSec=10s\n', 'KillMode=mixed\n',
              'TimeoutStopSec=120s\n', 'StandardOutput=journal\n', 'StandardError=journal\n',
              '\n[Install]\n', 'WantedBy=default.target\n']
    return ''.join(lines)


def systemctl(*arguments):
    executable = shutil.which('systemctl')
    if not executable:
        raise ConfigError('systemctl is missing; use reicloud run in the foreground.')
    return subprocess.run([executable, '--user', *arguments], check=True)


def install(paths, jobs=2, *, dry_run=False):
    paths.load()
    content = render_unit(paths, jobs)
    if dry_run:
        print(content, end='')
        return
    if not shutil.which('rclone'):
        raise ConfigError('rclone is missing. Install it and put it on PATH before installing the service.')
    target = unit_path(paths)
    target.parent.mkdir(parents=True, exist_ok=True)
    if target.is_symlink() or (target.exists() and not target.read_text().startswith(HEADER)):
        raise ConfigError(f'Refusing to replace an unmanaged service file: {target}')
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=target.parent, delete=False) as stream:
            temporary = stream.name
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, target)
    finally:
        if temporary and os.path.exists(temporary):
            os.unlink(temporary)
    systemctl('daemon-reload')
    systemctl('enable', unit_name(paths))
    get_cli_logger().info('Installed and enabled %s. No start or restart was requested. Run reicloud service start.', target)


def control(paths, action):
    if action == 'path':
        print(unit_path(paths))
        return
    if action not in ('start', 'stop', 'status', 'enable', 'disable'):
        raise ConfigError(f'Unsupported service action: {action}')
    target = unit_path(paths)
    if not target.is_file() or target.is_symlink() or not target.read_text().startswith(HEADER):
        raise ConfigError('Service is not installed for this configuration. Run reicloud service install.')
    arguments = (action, '--no-pager', unit_name(paths)) if action == 'status' else (action, unit_name(paths))
    systemctl(*arguments)
    get_cli_logger().info('Service %s: %s', action, unit_name(paths))
